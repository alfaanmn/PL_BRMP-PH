-- DOKUMENTASI AKTUAL SCHEMA & POLICY TABEL notifikasi
-- CATATAN: File ini HANYA bersifat dokumentasi baseline dan TIDAK UNTUK DIJALANKAN ULANG ke database.
-- Skema dan RLS di bawah ini telah terpasang secara aktual di Supabase.

CREATE TABLE IF NOT EXISTS public.notifikasi (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    judul character varying(255) NOT NULL,
    pesan text NOT NULL,
    link character varying(255),
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now())
);

-- RLS sudah aktif pada tabel ini
ALTER TABLE public.notifikasi ENABLE ROW LEVEL SECURITY;

-- FAKTA POLICY AKTUAL (DOKUMENTASI):
-- 1. SELECT: Diizinkan untuk pemilik (auth.uid() = user_id) atau administrator via function is_admin().
-- 2. UPDATE: Diizinkan untuk pemilik (auth.uid() = user_id) atau administrator via function is_admin().
-- 3. DELETE: Diizinkan untuk pemilik (auth.uid() = user_id) atau administrator via function is_admin().
-- 4. INSERT: HANYA administrator via function is_admin() (with check).
--
-- KONSEKUENSI PADA KODE:
-- Karena user biasa tidak memiliki hak INSERT langsung, seluruh pembuatan notifikasi dari sistem
-- di sisi server WAJIB menggunakan admin client (service role / createAdminClient).
-- Seluruh query SELECT dan PATCH untuk lonceng pengguna dan admin WAJIB menambahkan filter eksplisit
-- user_id = auth.uid() dari session yang login.
